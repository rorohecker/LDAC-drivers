param(
    [Parameter(Mandatory = $true)]
    [string]$HardwareId,
    [string]$OutputPath = ''
)
$ErrorActionPreference = 'Stop'
$projectRoot = Split-Path $PSScriptRoot -Parent
$template = Join-Path $projectRoot 'driver\xm5ldac.inf.in'
if (!(Test-Path $template)) { throw "Missing template: $template" }

$id = $HardwareId.Trim()
if ([string]::IsNullOrWhiteSpace($id)) { throw 'HardwareId is empty.' }
if ($id -eq '__HEADPHONE_SERVICE_HARDWARE_ID__') { throw 'Placeholder HardwareId is not allowed.' }
if ($id -match 'Intel|8087|MS_BTHPORT|MS_BTHBRB|Wireless Bluetooth') {
    throw "Refusing HardwareId that looks like a Bluetooth radio adapter: $id"
}
if ($id -notmatch '^BTHENUM\\\{0000110b-0000-1000-8000-00805f9b34fb\}(?:_[A-Za-z0-9]+&[A-Fa-f0-9]+)*\z') {
    throw "Refusing HardwareId that is not a Bluetooth Audio Sink service (UUID 0000110b): $id"
}

if ([string]::IsNullOrWhiteSpace($OutputPath)) {
    $OutputPath = Join-Path $projectRoot 'driver\xm5ldac.inf'
}

$text = Get-Content -Raw -Path $template
if ($text -notmatch [regex]::Escape('__HEADPHONE_SERVICE_HARDWARE_ID__')) {
    throw 'Template is missing __HEADPHONE_SERVICE_HARDWARE_ID__ placeholder.'
}
$generated = $text.Replace('__HEADPHONE_SERVICE_HARDWARE_ID__', $id)
# Mark generated file so it is never mistaken for the editable template.
$header = "; GENERATED by tools/generate-inf.ps1 - do not edit by hand.`r`n; Source template: driver/xm5ldac.inf.in`r`n; HardwareId: $id`r`n"
if ($generated -notmatch '^; GENERATED') {
    $generated = $header + $generated
}
Set-Content -Path $OutputPath -Value $generated -Encoding ascii -NoNewline
Write-Output "Wrote $OutputPath"
Write-Output "HardwareId=$id"
